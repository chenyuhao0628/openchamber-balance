export const serverText = (text: string | null | undefined, translate: Translate = t): string | null => {
  if (text == null || !/[\u4e00-\u9fff]/.test(text)) return text ?? null;
  if (Object.prototype.hasOwnProperty.call(messages, text)) return translate(text);
  for (const item of dynamicPatterns) {
    const match = text.match(item.pattern);
    if (match) return translate(item.template, item.values(match));
  }
  return text;
};
